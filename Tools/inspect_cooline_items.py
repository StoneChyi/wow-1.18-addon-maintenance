"""Inspect local 1.12 item definitions and generate a reviewed Cooline ID map.

Reads itemcache.wdb and extracted Spell.dbc; never copies the cache into Git.
Only the explicitly reviewed categories below are eligible. --lua emits the
small addon whitelist, not names, account data or full item definitions.
"""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import struct

from inspect_cooline_shared import read_dbc


CATEGORIES = {4, 24, 94, 103, 831, 1051, 1141, 1149, 1153, 1155, 1172, 1175}
# Missing cache entries: the standard healthstone ranks/talent variants. Their
# on-use spell IDs are verified against the client's create-item spell effects;
# Turtle's official class patch confirms the shared cooldown across all ranks.
HEALTHSTONES = dict(zip(
    [5512, 5511, 5509, 5510, 9421] + list(range(19004, 19014)),
    [6262, 6263, 5720, 5723, 11732] + list(range(23468, 23478)),
))


def read_items(path):
    raw = path.read_bytes()
    if len(raw) < 20 or raw[:4] != b'BDIW':
        raise ValueError('Unexpected 1.12 item cache header')
    position, items = 20, {}
    while position + 8 <= len(raw):
        item_id, length = struct.unpack_from('<II', raw, position)
        position += 8
        if not item_id or not length:
            break
        record = raw[position:position + length]
        if len(record) != length:
            raise ValueError('Truncated item definition')
        position += length
        cursor, names = 8, []
        for _ in range(4):
            end = record.index(0, cursor)
            names.append(record[cursor:end].decode('utf-8'))
            cursor = end + 1
        # 20 item properties, 10 stat pairs, 5 damage triples, 7 resistances,
        # weapon delay, ammunition type and ranged modifier, then 5 spell slots.
        spell_offset = cursor + (20 + 20 + 15 + 7 + 3) * 4
        slots = [struct.unpack_from('<6i', record, spell_offset + index * 24)
                 for index in range(5)]
        items[item_id] = {'name': names[0], 'slots': slots}
    return items, hashlib.sha256(raw).hexdigest()


def inspect(cache, dbc):
    items, cache_hash = read_items(cache)
    spells, _, spell_meta = read_dbc(dbc, 173)
    candidates, excluded_multi = {}, []
    for item_id, item in sorted(items.items()):
        if item_id > 100000:  # imported/variant IDs outside this client scope
            continue
        uses = []
        for spell, trigger, charges, own, category, shared in item['slots']:
            if not spell or trigger not in (0, 5):
                continue
            # Both negative fields mean the item inherits the spell defaults.
            # Explicit item-category overrides take precedence over Spell.dbc.
            if own < 0 and shared < 0 and spell in spells:
                own, shared, category = spells[spell][19], spells[spell][20], spells[spell][2]
            if category in CATEGORIES and shared > 3000:
                uses.append((category, spell, max(0, own) / 1000, shared / 1000))
        if len(uses) == 1:
            candidates[item_id] = uses[0]
        elif len(uses) > 1:
            excluded_multi.append(item_id)
    for item_id, spell_id in HEALTHSTONES.items():
        if item_id not in candidates:
            # Verify the create-item result exists in this exact client data.
            if not any(any(effect == 24 and created == item_id
                           for effect, created in zip(row[61:64], row[103:106]))
                       for row in spells.values()):
                raise ValueError('Unverified healthstone item ID: ' + str(item_id))
            if spell_id not in spells:
                raise ValueError('Missing healthstone on-use spell')
            candidates[item_id] = (1153, spell_id, 0, 120)
    for item_id, category in {13180: 24, 4390: 24, 10646: 24, 13446: 4,
                              13444: 4, 12662: 1172, 61675: 1172}.items():
        if candidates.get(item_id, (None,))[0] != category:
            raise ValueError('Reviewed reference item changed: ' + str(item_id))
    counts = defaultdict(int)
    for category, *_ in candidates.values():
        counts[category] += 1
    return candidates, {'cache_records_checked': len(items), 'cache_sha256': cache_hash,
                        'spell_dbc': spell_meta, 'item_count': len(candidates),
                        'category_counts': dict(sorted(counts.items())),
                        'excluded_ambiguous_items': excluded_multi}


def lua_source(candidates):
    lines = ['-- Reviewed item IDs: category, on-use spell, own CD, category CD (seconds).',
             '-- Generated by Tools/inspect_cooline_items.py; live API timings decide merging.',
             '-- Research: PluginHistory/Research/Cooline-shared-items-20261013.md',
             'cooline_shared_items = {']
    for item_id, data in sorted(candidates.items()):
        lines.append('    [%d] = {%s},' % (item_id, ', '.join('%g' % value for value in data)))
    lines.extend(['}', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, required=True)
    parser.add_argument('--spell-dbc', type=Path, required=True)
    parser.add_argument('--lua', type=Path)
    args = parser.parse_args()
    entries, summary = inspect(args.cache, args.spell_dbc)
    if args.lua:
        args.lua.write_text(lua_source(entries), encoding='utf-8', newline='\n')
    print(json.dumps(summary, ensure_ascii=True, indent=2))
