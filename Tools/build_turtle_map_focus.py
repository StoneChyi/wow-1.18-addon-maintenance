"""Build small cursor hit masks from the existing outdoor/city alpha assets.

No map art, source evidence, or client archives are rewritten. The 48x32 masks
keep pointer selection out of transparent ocean and overlapping map margins.
"""
import json
from PIL import Image
from build_turtle_seamless_map import ROOT, ADDON, decode_blp, lua, write


def build():
    manifest = json.loads((ROOT/'PluginHistory/Research/TurtleSeamlessMap-0.2.0资源-20261024.json').read_text(encoding='utf-8'))
    masks = {}
    for m in manifest['maps']:
        if m['kind']!='surface':
            continue
        canvas = Image.new('L',(1002,668))
        for index in range(12):
            image = decode_blp((ADDON/'Art'/f"v2_{m['id']}_{index+1}.blp").read_bytes()).convert('RGBA')
            canvas.paste(image.getchannel('A'),((index%4)*256,(index//4)*256))
        small = canvas.resize((48,32),Image.Resampling.BOX)
        digits = []
        for y in range(32):
            for x in range(0,48,4):
                value = sum((1<<bit) for bit in range(4) if small.getpixel((x+bit,y))>=32)
                digits.append(format(value,'x'))
        masks[m['id']] = [48,32,''.join(digits)]
        assert any(c!='0' for c in masks[m['id']][2]),m['file']
    assert len(masks)==60
    source = '-- Generated by Tools/build_turtle_map_focus.py from installed atlas alpha.\n'
    source += 'TurtleSeamlessMap_Focus = '+lua(masks)+'\n'
    write(ADDON/'FocusData.lua',source.encode('utf-8'))
    print('Built 60 cursor masks (48x32); original art and extraction unchanged.')


if __name__=='__main__':
    build()
